#!/usr/bin/env python3
"""generate the public challenge data from the private source.
builds a puzzle that has no plaintext flags included!! all hashed instead
    python tools/build.py
"""
import hashlib   # sha-256 hashing
import json      # reading and writing json
import pathlib   # file paths that work on windows and linux alike
import sys       # for exit codes and error output

# walk up from this file (tools/build.py) to the repo root
ROOT = pathlib.Path(__file__).resolve().parent.parent

SOURCE = ROOT / "challenges.source.json"   # private: has plaintext flags
OUTPUT = ROOT / "data" / "challenges.js"   # public: ships to the site

# the only fields allowed to reach the public file. "flag" is deliberately absent to limit leaks
PUBLIC_FIELDS = ("id", "name", "category", "tier", "brief", "data", "data_label", "hints")


def main():
    # read the private file and turn its json text into python dicts and lists
    src = json.loads(SOURCE.read_text())

    message = src.get("message", "")   # string revealed in the hex map
    challenges = src["challenges"]     # the list of challenge dicts

    out = []   # public entries get collected here

    # enumerate gives us both the position (i) and the challenge (ch)
    for i, ch in enumerate(challenges):

        # build a new dict containing only the public fields
        # because "flag" isn't in PUBLIC_FIELDS, it can't be copied by accident
        entry = {k: ch.get(k) for k in PUBLIC_FIELDS}

        # hash the flag, .encode() turns the string into bytes, which is what sha256 requires, .hexdigest() gives the hash back as readable text
        entry["hash"] = hashlib.sha256(ch["flag"].encode()).hexdigest()

        # which character of `message` this challenge reveals when solved.
        # ord() converts a character to its number: ord("A") is 65.
        # if message is shorter than the challenge list, fall back to 0x2E (".") as a safety net
        entry["byte"] = ord(message[i]) if i < len(message) else 0x2E

        # position in the list, used to order the hex map
        entry["offset"] = i

        out.append(entry)

    # create the data/ folder if it isn't there yet
    OUTPUT.parent.mkdir(exist_ok=True)

    # write the javascript file, json.dumps turns our list back into json text;
    # the "window.CHALLENGES = " prefix makes it loadable by a plain <script> tag
    OUTPUT.write_text(
        "// GENERATED by tools/build.py - do not edit by hand.\n"
        f"window.CHALLENGES = {json.dumps(out, indent=2)};\n"
    )

    # safety net: read back what we wrote and make sure no plaintext flag is
    # in it. if one is, delete the file rather than leave a leaky one on disk
    body = OUTPUT.read_text()
    for ch in challenges:
        if ch["flag"] in body:
            print(f"abort: plaintext flag for {ch['id']} leaked", file=sys.stderr)
            OUTPUT.unlink()
            return 1   # non-zero exit code = failure

    print(f"wrote {OUTPUT.relative_to(ROOT)} - {len(out)} challenges")
    return 0   # zero = success


if __name__ == "__main__":
    # only run main() when this file is executed directly
    sys.exit(main())

